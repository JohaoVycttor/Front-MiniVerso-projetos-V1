const text=v=>typeof v==='string'&&v.length<=10000;
const list=(v,check)=>Array.isArray(v)&&v.length<=30&&v.every(check);
const link=v=>text(v)&&/^\/(?![\/\\])/.test(v)&&!/[\r\n\\]/.test(v);
const image=v=>text(v)&&(v===''||link(v)||/^https:\/\/[^\s]+$/.test(v));
export function validateSolutions(v){
 if(!v||!/^#[\da-f]{6}$/i.test(v.background)||!/^#[\da-f]{6}$/i.test(v.accent))return false;
 if(v.pageTitle!==undefined&&!text(v.pageTitle))return false;
 if(v.heroMeta!==undefined&&(!v.heroMeta||!Object.values(v.heroMeta).every(text)))return false;
 const ids=new Set();
 return list(v.sections,s=>{
  if(!s||!text(s.id)||ids.has(s.id)||typeof s.enabled!=='boolean'||![s.label,s.title,s.highlight].every(text))return false;ids.add(s.id);
  if(s.description!==undefined&&!text(s.description))return false;
  if(['catalog','banner'].includes(s.type)&&(!image(s.image)||!text(s.imagePosition)||typeof s.overlay!=='number'||s.overlay<0||s.overlay>1||s.video!==undefined&&!image(s.video)||s.poster!==undefined&&!image(s.poster)))return false;
  switch(s.type){
   case 'catalog':return [1,2].includes(s.columns)&&text(s.button)&&text(s.benefitsLabel)&&list(s.cards,c=>c&&[c.title,c.description,c.icon].every(text)&&typeof c.wide==='boolean'&&link(c.href)&&list(c.benefits,text)&&list(c.tags,text))&&optionalText(s.heroEyebrow,s.heroActionLabel,s.heroScrollLabel,s.cardsTitle,s.cardsHighlight,s.cardsDescription,s.imageAlt)&&optionalList(s.specialties,text);
   case 'comparison':return Array.isArray(s.headers)&&s.headers.length===3&&s.headers.every(text)&&list(s.rows,r=>r&&[r.objective,r.format,r.delivery].every(text));
   case 'process':return [1,2,3,4].includes(s.columns)&&list(s.steps,r=>r&&[r.title,r.description].every(text));
   case 'banner':return text(s.button)&&link(s.href);
   default:return false;
  }
 });
}
function optionalText(...values){return values.every(value=>value===undefined||text(value))}
function optionalList(value,check){return value===undefined||list(value,check)}
