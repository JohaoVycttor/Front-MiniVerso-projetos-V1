export function validateStudio(v){
if(!v||!/^#[\da-f]{6}$/i.test(v.background)||!/^#[\da-f]{6}$/i.test(v.accent)||!Array.isArray(v.sections)||v.sections.length>30)return false;
const text=x=>typeof x==='string'&&x.length<=10000;
const media=x=>text(x)&&(x===''||/^(\/(?!\/)|https:\/\/)/.test(x));
if(v.pageTitle!==undefined&&!text(v.pageTitle))return false;
if(v.heroMeta!==undefined&&(!v.heroMeta||!Object.values(v.heroMeta).every(text)))return false;
if(v.projectSection!==undefined&&(!v.projectSection||!['label','title','highlight','actionLabel'].every(k=>text(v.projectSection[k]))))return false;
const ids=new Set();const strings=a=>a.every(x=>typeof x==='string'&&x.length<=10000);
return v.sections.every(s=>{if(!s||typeof s.id!=='string'||ids.has(s.id))return false;ids.add(s.id);if(!['intro','cards','cta'].includes(s.type)||typeof s.enabled!=='boolean'||!strings([s.title,s.highlight,s.label]))return false;if(s.description!==undefined&&!strings([s.description]))return false;if(s.type==='cards')return [1,2,3,4].includes(s.columns)&&['lines','cards','tinted'].includes(s.layout)&&Array.isArray(s.cards)&&s.cards.length<=24&&s.cards.every(c=>c&&strings([c.title,c.description,c.icon]));if(!strings([s.image,s.imagePosition])||!media(s.image)||s.imageAlt!==undefined&&!text(s.imageAlt)||typeof s.overlay!=='number'||s.overlay<0||s.overlay>1||s.video!==undefined&&!media(s.video)||s.poster!==undefined&&!media(s.poster))return false;if(s.type==='cta')return strings([s.button,s.href])&&/^\/(?!\/)/.test(s.href)&&(!s.buttonNote||text(s.buttonNote));return ['split','stacked'].includes(s.layout)&&strings([s.storyTitle,s.storyHighlight,s.noteTitle,s.note])&&[s.tags,s.paragraphs].every(a=>Array.isArray(a)&&a.length<=30&&strings(a))});
}
